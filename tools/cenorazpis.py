#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Пресъздава ценоразписа на артикулите от ЖИВИТЕ данни на платформата.

Защо изобщо: до 25.10.2026 ценоразписът беше xlsx в Драйв, снет на ръка на
14.09. Оттогава цените се менят в master.json, а файлът не — и вече лъжеше
(Трамезини Салами 535 стоеше с една цена в него и с шест в master.json).
Който го отвореше да сверява цена, виждаше стара истина.

Източниците са три и всичките се четат от живата страница, за да е точно
това, с което работи приложението:
  master.json      - код, име, категория, цени по ценови групи
  LABEL_META       - баркод (EAN-13) и срок на годност Варна/Бургас
  articles_db.json - кои артикули имат данни за етикет

Изходът е списък от редове (JSON), който се записва в лист ЦЕНОРАЗПИС на
Bandits_REGISTAR_LIVE. Писането в листа става отвън - тук само се смята.

Пуска се:  python3 tools/cenorazpis.py [изходен .json]
"""

import json
import re
import subprocess
import sys
import tempfile
import os

СТРАНИЦА = "https://bandits-import.netlify.app/"

# Реда на колоните с цени: ключът в master.json -> заглавието в листа.
ГРУПИ = [
    ("Дребно 300", "Дребно 300"),
    ("ЦГ2", "ЦГ2 Сити"),
    ("ЦГ4", "ЦГ4 Стар"),
    ("ЦГ1", "ЦГ1"),
    ("Дребно други", "Дребно други"),
    ("Бургас", "Бургас"),
]

ЗАГЛАВИЯ = (["Код", "Артикул", "Категория", "Нето", "Баркод (EAN-13)"]
            + [з for _, з in ГРУПИ]
            + ["Срок Варна", "Срок Бургас", "Етикет", "Бележка"])

# Реда на категориите, както е бил в стария файл - за да се чете еднакво.
РЕД_КАТЕГОРИИ = ["Салати", "Тортия", "Трамезини", "Чиабата", "Принцеса",
                 "Десерти", "Крейзи", "Багети", "ВЕГА"]

# Бележки, писани от човек. Не могат да се изведат от данните, затова се
# пазят тук - иначе всяко пресъздаване ги трие.
РЪЧНИ_БЕЛЕЖКИ = {
    "521": "1 етикет на 10 бр. (тарелка)",
    "522": "1 етикет на 10 бр. (тарелка)",
    "673": "нов артикул от 14.09.2026 — замества Крейзи чабата за Бургас",
}

ЧЕТЕЦ = r"""
const {chromium} = require('playwright');
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage();
  await p.goto('%s?x=' + Date.now(), {waitUntil: 'domcontentloaded'});
  await p.waitForTimeout(6000);
  const d = await p.evaluate(async () => {
    await loadMaster();
    const db = await fetch('articles_db.json?x=' + Date.now()).then(r => r.json()).catch(() => ({}));
    return {articles: MASTER.articles, labelMeta: LABEL_META, db,
            orderMap: MASTER.orderMap, objects: MASTER.objects};
  });
  console.log(JSON.stringify(d));
  await b.close();
})();
"""


def прочети_живите_данни():
    """Чете трите източника от живата страница."""
    with tempfile.NamedTemporaryFile("w", suffix=".js", delete=False) as f:
        f.write(ЧЕТЕЦ % СТРАНИЦА)
        път = f.name
    try:
        out = subprocess.run(["node", път], capture_output=True, text=True, timeout=180)
        if out.returncode != 0:
            raise RuntimeError("страницата не се прочете: " + (out.stderr or "")[-500:])
        return json.loads(out.stdout.strip().splitlines()[-1])
    finally:
        os.unlink(път)


НЕТО = re.compile(r"(\d+(?:[.,]\d+)?)\s*(?:гр?\.?|g)\s*\.?\s*$", re.IGNORECASE)

# Същата нормализация, с която страницата свързва артикул със записа му за
# етикет. Имената се разминават по „нет.кол" и грамажа („Салата Овчарска 320 г."
# срещу „Салата Овчарска нет.кол 320 гр."), затова сравнението е по голото име.
_НОРМ = [(re.compile(r"НЕТНО|НЕТ\.?"), ""), (re.compile(r"КОЛ\.?"), ""),
         (re.compile(r"\d+\s*ГР?\.?"), ""), (re.compile(r"[.,№]"), ""),
         (re.compile(r"\s+"), " ")]


def голо_име(s):
    t = str(s or "").upper()
    for рег, зам in _НОРМ:
        t = рег.sub(зам, t)
    return t.strip()


def нето_от_името(име):
    """„Салата Фусили нет.кол 280 гр." -> „280 г". Празно, ако няма грамаж."""
    m = НЕТО.search(str(име or "").strip())
    return (m.group(1).replace(",", ".") + " г") if m else ""


def построй(данни):
    арт = данни["articles"]
    мета = данни.get("labelMeta") or {}
    db = данни.get("db") or {}
    сЕтикет = {голо_име(v.get("name")) for v in db.values()}

    редове = []
    for a in арт:
        код = str(a.get("code", ""))
        име = str(a.get("name", ""))
        цени = a.get("prices") or {}
        m = мета.get(код) or {}
        ean = m.get("ean") or ""

        бележки = []
        if код in РЪЧНИ_БЕЛЕЖКИ:
            бележки.append(РЪЧНИ_БЕЛЕЖКИ[код])
        if not ean:
            бележки.append("няма баркод")
        if str(a.get("cat", "")) == "ВЕГА":
            бележки.append("стока за препродажба, не се етикетира")

        редове.append({
            "Код": код,
            "Артикул": име,
            "Категория": a.get("cat", ""),
            "Нето": нето_от_името(име),
            "Баркод (EAN-13)": ean,
            **{з: цени.get(к, "") for к, з in ГРУПИ},
            "Срок Варна": (f"{m['srokV']} дни" if m.get("srokV") else "—"),
            "Срок Бургас": (f"{m['srokB']} дни" if m.get("srokB") else "—"),
            "Етикет": име if голо_име(име) in сЕтикет else "—",
            "Бележка": "; ".join(бележки),
        })

    поредност = {к: i for i, к in enumerate(РЕД_КАТЕГОРИИ)}
    редове.sort(key=lambda r: (поредност.get(r["Категория"], 99), r["Артикул"]))
    return редове


def провери(редове, данни):
    """Проверките под таблицата."""
    без_баркод = [r["Код"] for r in редове if not r["Баркод (EAN-13)"]]

    по_баркод = {}
    for r in редове:
        if r["Баркод (EAN-13)"]:
            по_баркод.setdefault(r["Баркод (EAN-13)"], []).append(r["Код"])
    споделени = {k: v for k, v in по_баркод.items() if len(v) > 1}

    без_цена = [r["Код"] for r in редове if not any(r[з] != "" for _, з in ГРУПИ)]

    # Артикул без данни за етикет - няма да се отпечата както трябва.
    db = данни.get("db") or {}
    сЕтикет = {голо_име(v.get("name")) for v in db.values()}
    без_етикет = [f"{r['Код']} {r['Артикул']}" for r in редове
                  if r["Категория"] != "ВЕГА" and голо_име(r["Артикул"]) not in сЕтикет]

    # ПОРЪЧВАЕМ артикул без цена за ценова група, която обекти реално ползват.
    # Точно това спря заявките за 26 и 27.10: Тортия Салами беше в таблицата на
    # Мони, но нямаше цена за „Дребно 300", а 51 обекта са в тази група. Докато
    # никой не го поръча, нищо не личи; поръча ли го - пада цялата заявка.
    поръчваеми = {str(v) for v in (данни.get("orderMap") or {}).values() if v}
    групи_в_употреба = sorted({o.get("pg") for o in (данни.get("objects") or [])
                               if o.get("pg")})
    брой_обекти = {g: sum(1 for o in (данни.get("objects") or []) if o.get("pg") == g)
                   for g in групи_в_употреба}
    озаглавие = {к: з for к, з in ГРУПИ}
    дупки = []
    for r in редове:
        if r["Код"] not in поръчваеми:
            continue
        липсват = [g for g in групи_в_употреба if r.get(озаглавие.get(g, g), "") == ""]
        if липсват:
            дупки.append(f"{r['Код']} {r['Артикул']} — няма цена за "
                         + ", ".join(f"{g} ({брой_обекти[g]} обекта)" for g in липсват))

    return [
        ("Артикули без баркод", len(без_баркод), ", ".join(без_баркод)),
        ("Баркод, ползван от повече артикули", len(споделени),
         " | ".join(f"{k}: {', '.join(v)}" for k, v in sorted(споделени.items()))),
        ("Артикули без нито една цена", len(без_цена), ", ".join(без_цена)),
        ("Артикули без данни за етикет", len(без_етикет), " | ".join(без_етикет)),
        ("ПОРЪЧВАЕМ артикул без цена за ценова група в употреба — спира заявката",
         len(дупки), " | ".join(дупки)),
    ]


def запиши_csv(път, редове, проверки):
    """CSV-то стои до сайта, а листът ЦЕНОРАЗПИС го тегли с IMPORTDATA.

    Така нищо не се преписва на ръка и няма график, който да се чуди дали е
    минал: Google презарежда адреса сам. Единственото, което трябва да стане
    при промяна на цена, е сайтът да се пусне наново - а той и без това се
    пуска, щом master.json се промени.
    """
    import csv
    from datetime import datetime, timezone, timedelta
    сега = datetime.now(timezone(timedelta(hours=2))).strftime("%d.%m.%Y %H:%M")
    with open(път, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["ЦЕНОРАЗПИС НА АРТИКУЛИТЕ · Bandits ООД"])
        w.writerow(["Прави се автоматично от живите данни на платформата. "
                    "НЕ се пише на ръка — всяка ръчна промяна изчезва при обновяване."])
        w.writerow([f"Последно обновен: {сега} · източници: master.json (цени), "
                    f"LABEL_META (баркод и срок), articles_db.json (етикети) · "
                    f"артикули: {len(редове)}"])
        w.writerow([])
        w.writerow(ЗАГЛАВИЯ)
        for r in редове:
            w.writerow([r.get(k, "") for k in ЗАГЛАВИЯ])
        w.writerow([])
        w.writerow(["ПРОВЕРКИ"])
        w.writerow(["Проверка", "Брой", "Какво точно"])
        for име, брой, какво in проверки:
            w.writerow([име, брой, какво])
        w.writerow([])
        w.writerow(["Споделен баркод не е задължително грешка — при малки артикули "
                    "понякога се ползва общ EAN."])
        w.writerow(["ВЕГА са стока за препродажба — нямат баркод и не се етикетират."])
        w.writerow(["„Поръчваем артикул без цена“ е най-опасната проверка: докато никой "
                    "не го поръча, нищо не личи; поръча ли го — пада цялата заявка."])


def main():
    данни = прочети_живите_данни()
    редове = построй(данни)
    проверки = провери(редове, данни)
    изход = {"заглавия": ЗАГЛАВИЯ, "редове": редове, "проверки": проверки,
             "брой": len(редове)}
    път = sys.argv[1] if len(sys.argv) > 1 else "cenorazpis.json"
    with open(път, "w", encoding="utf-8") as f:
        json.dump(изход, f, ensure_ascii=False, indent=1)
    csv_път = sys.argv[2] if len(sys.argv) > 2 else "cenorazpis.csv"
    запиши_csv(csv_път, редове, проверки)
    print(f"{len(редове)} артикула -> {път} и {csv_път}")
    for име, брой, какво in проверки:
        print(f"  {име}: {брой}" + (f"  [{какво[:160]}]" if брой else ""))


if __name__ == "__main__":
    main()
